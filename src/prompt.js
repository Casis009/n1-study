/* 문제 생성 프롬프트. 출력 JSON 스키마는 sets.js의 normalizeQ와 맞춰야 한다. */
import { KINDS, TOPICS } from "./kinds.js";

export function buildPrompt(gen, weakList){
  const k = gen.kind, n = gen.count;
  const topic = gen.topic.trim() || TOPICS[Math.floor(Math.random()*TOPICS.length)];
  const spec = {
    kanji_reading: `한자 읽기(漢字読み) ${n}문항. 각 stem은 N1급 한자어 하나를 __밑줄__로 감싼 일본어 문장. choices는 히라가나 읽기 4개(장음·촉음·탁음·요음을 비튼 헷갈리는 오답, 예: きょうい/きょうえ/けいい/きょい). passage는 빈 문자열.`,
    context: `문맥 규정(文脈規定) ${n}문항. 각 stem은 （　　）가 있는 일본어 문장, choices는 같은 품사의 N1급 어휘 4개(의미가 비슷하거나 한자가 겹치는 것). passage는 빈 문자열.`,
    paraphrase: `유의어(言い換え類義) ${n}문항. 각 stem은 단어나 짧은 표현 하나를 __밑줄__로 감싼 일본어 문장, choices는 밑줄 부분과 의미가 가장 가까운 것을 고르는 일본어 표현 4개. passage는 빈 문자열.`,
    usage: `용법(用法) ${n}문항. 각 stem은 「단어」 하나만(예: 「手分け」), choices는 그 단어를 쓴 일본어 문장 4개이며 그중 하나만 자연스럽다. 오답 문장은 비슷한 뜻의 다른 단어를 써야 할 자리에 그 단어를 넣은 것. passage는 빈 문자열.`,
    text_grammar: `글의 문법(文章の文法). 수필·논설풍 지문 1개(일본어 600~750자)에 빈칸 5개를 （１）～（５）로 표시. 문항 5개는 각 빈칸에 들어갈 표현(접속사, 지시어, 문말 표현, 수동·사역, 문법 형식) 고르기. stem은 "（１）に入るのはどれか。" 형식.`,
    info_search: `정보 검색(情報検索). 실용문 1개(모집 요강·이용 안내·요금 규정·공모 안내 등, 일본어 600~800자). 항목은 줄바꿈과 「・」「※」「1.」로 정리하고 표나 마크다운은 쓰지 않는다. 문항 2개는 구체적인 인물 조건(나이, 날짜, 금액, 자격 등)을 제시하고 조건에 맞는 것을 고르게 한다. 오답은 ※ 단서 조건을 놓치면 고르게 되는 함정으로.`,
    grammar_blank: `문법 형식 판단(文法形式の判断) ${n}문항. 각 문장 속 （　　）에 들어갈 가장 알맞은 표현을 고르는 문제. passage는 빈 문자열.`,
    grammar_order: `문장 배열(文の組み立て) ${n}문항. stem에는 「＿＿＿ ＿＿＿ ＿★＿ ＿＿＿」처럼 빈칸 4개를 넣고 그중 하나에만 ★를 붙인다(★ 위치는 문항마다 바꿀 것). choices는 그 4칸에 들어갈 조각 4개, answer는 ★ 칸에 들어가는 조각. explanation.why에 완성 문장과 올바른 순서를 쓴다. choiceNotes에는 각 조각이 몇 번째 칸인지 적는다. passage는 빈 문자열.`,
    reading_short: `단문 내용 이해(内容理解・短文). 논설·수필풍 지문 1개(일본어 230~300자)와 문항 2개(필자의 생각, 밑줄 의미 또는 이유).`,
    reading_mid: `중문 내용 이해(内容理解・中文). 지문 1개(일본어 500~600자, 2~3단락)와 문항 3개(밑줄 이유, 밑줄 의미, 필자의 주장).`,
    reading_long: `주장 이해(主張理解・長文). 추상도가 높은 논설 지문 1개(일본어 850~1000자, 4~5단락)와 문항 3개(밑줄 의미, 이유, 필자가 가장 말하고 싶은 것).`,
    integrated: `통합 이해(統合理解). 같은 주제에 대해 입장이 다른 두 글 A와 B(각 일본어 250~320자). passage는 "A\\n(본문)\\n\\nB\\n(본문)" 형식. 문항 2개(A와 B의 공통 인식, A와 B의 입장 차이).`
  }[k];
  const isVocab = !!KINDS[k].vocab;
  const weak = gen.weak ? weakList : [];
  return `당신은 JLPT N1 출제 위원이자 한국인 학습자를 가르치는 일본어 강사입니다. 아래 조건으로 새 연습 문제 세트를 만드세요.

[유형] ${spec}
[주제] ${topic}
[무작위 시드] ${Math.floor(Math.random()*1e6)} (매번 다른 내용으로)
${weak.length ? `[학습자 약점 ${isVocab ? "어휘" : "문법"}] 자연스럽게 가능하면 다음 ${isVocab ? "어휘(또는 비슷한 말)" : "문법"}을 섞어 출제: ${weak.join(", ")}\n` : ""}
[규칙]
- 지문·문제·선택지는 실제 JLPT N1 수준과 형식의 자연스러운 일본어로 새로 쓴다. 기출문제나 출판물 문장을 그대로 옮기지 않는다.
- 정답은 반드시 하나만 명확해야 한다. 오답은 본문 표현을 비틀거나 일부만 맞는 그럴듯한 함정으로 만든다.
- 밑줄 부분은 passage 안에서 __밑줄 문구__ 처럼 밑줄 두 개로 감싸고, 문제에서는 「밑줄 문구」로 가리킨다.
- 해설(ex)은 모두 한국어로 쓰되, 일본어 표현은 원문 그대로 인용한다. 선택지를 번호로 부르지 말고 내용으로 가리킨다.
  - translation: {full: 정답을 넣은 완성 문장(빈칸 유형은 빈칸을 채운 문장, 문장 배열은 올바른 순서로 완성한 문장, 독해는 질문 문장, 용법은 정답 문장), ko: full의 한국어 번역}
  - choicesKo: choices와 같은 순서로 정확히 4개. {reading: 20자 이하 선택지에 한자가 있으면 전체 히라가나 읽기(문장 길이 선택지나 한자가 없으면 ""), ko: 선택지의 한국어 뜻}
  - why: 정답의 근거. 근거가 되는 본문 문장을 「」로 인용하고 설명(2~4문장).
  - kanji: 지문·문제·선택지에 나온 N1급 한자어 4~8개(선택지의 N1급 한자어도 포함). {word: 한자 표기, reading: 히라가나 읽기, meaning: 한국어 뜻}
  - grammar: 핵심 문법·표현 1~4개. {pattern: "〜にすぎない" 형태, meaning: 한국어 뜻과 쓰임, example: 짧은 일본어 예문 + (한국어 해석)}
  - pattern: 이 문제의 출제 패턴(질문 유형, 정답 근거가 보통 어디에 있는지) 1~2문장.
  - tip: 실전 풀이 요령 1~3문장.
  - choiceNotes: choices와 같은 순서로 정확히 4개. 각 선택지가 왜 정답이거나 오답인지 한 문장.
  - (ex 밖, 문항에) gloss: stem과 choices에 나온 N2~N1급 단어 3~8개(기초 단어 제외). {w: 문장에 나온 그대로의 표기(활용형 그대로, 문장 안에 정확히 있어야 함), r: w의 히라가나 읽기, m: 한국어 뜻}
  - (ex 밖, 문항에) patternTags: 이 문항이 묻는 핵심 문법 형태나 어휘 1~3개. 예: ["〜にすぎない"], ["手分け"]. 통계용이라 표기를 일정하게.
  - compare: 헷갈리기 쉬운 비슷한 말 비교 ${isVocab ? "2~4개 (필수)" : "0~3개 (필요할 때만, 없으면 빈 배열)"}. {word: 표기, reading: 히라가나, meaning: 한국어 뜻, note: 차이점과 대표 쓰임 한 문장}
${isVocab ? "  - 문자·어휘 유형에서 grammar는 관련 관용 표현·연어(예: 「手分けして探す」)를 넣고, 없으면 빈 배열.\n" : ""}
- answer는 0부터 시작하는 정답 선택지 인덱스.
- 지문이 있으면 최상위에 passageKo(지문 전체 한국어 번역, 단락 줄바꿈 유지)와 passageGloss(지문 속 N2~N1급 단어, 단락마다 3~8개, gloss와 같은 형식)를 넣는다. 지문이 없으면 ""와 [].

[출력] 다른 말 없이 JSON 하나만:
{"title":"일본어로 된 짧은 세트 제목","topic":"${topic}","passage":"지문(문법 유형은 빈 문자열)","passageKo":"","passageGloss":[{"w":"","r":"","m":""}],"questions":[{"stem":"문제 문장","choices":["","","",""],"answer":0,"patternTags":[""],"gloss":[{"w":"","r":"","m":""}],"ex":{"translation":{"full":"","ko":""},"why":"","choicesKo":[{"reading":"","ko":""},{"reading":"","ko":""},{"reading":"","ko":""},{"reading":"","ko":""}],"kanji":[{"word":"","reading":"","meaning":""}],"grammar":[{"pattern":"","meaning":"","example":""}],"pattern":"","tip":"","choiceNotes":["","","",""],"compare":[{"word":"","reading":"","meaning":"","note":""}]}}]}`;
}

/* 면접 답변을 보고 예상 꼬리 질문 5개. 출력은 sets.js의 normalizeFollowups와 맞춘다. */
export function buildFollowupPrompt(catJp, question, text){
  return `당신은 일본 기업의 채용 면접관이자, 한국인 지원자의 일본어 면접 준비를 돕는 코치입니다.
아래는 지원자가 준비한 면접 질문과 일본어 답변입니다. 이 답변을 들은 면접관이 이어서 물어볼 법한 꼬리 질문(深掘り質問) 5개를 만드세요.

[질문 유형] ${catJp || "その他"}
[질문] ${question}
[지원자 답변]
${text}

[규칙]
- 답변 속 구체적인 내용(경험, 숫자, 회사·직무, 동기, 약점, 공백 기간 등)을 짚어 파고드는 질문 위주로 만든다. 답변과 상관없는 일반 질문은 최대 1개.
- 답하기 곤란한 압박 질문을 1개 이상 넣는다(답변의 모순, 약점, 근거가 약한 부분).
- q: 실제 일본 면접관이 쓰는 자연스러운 정중체 일본어 한 문장(필요하면 존경어).
- ko: q의 한국어 번역.
- intent: 면접관이 이 질문으로 확인하려는 것(한국어 한 문장).
- point: 답할 때 넣으면 좋은 내용과 주의할 점(한국어 1~2문장).
- 지원자 답변의 일본어를 고치거나 점수를 매기지 않는다.

[출력] 다른 말 없이 JSON 하나만:
{"items":[{"q":"","ko":"","intent":"","point":""}]}`;
}
